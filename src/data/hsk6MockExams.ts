import { ExamLesson, Question, ReadingPassage } from '../types';
import { LessonItem, LessonSection } from '../types/lesson';

type ChoiceRow = {
  id: string;
  number: number;
  prompt: string;
  correctAnswer: string;
  options: Array<{ id: string; text: string }>;
};

const optionList = (values: string[]) => values.map((text, index) => ({
  id: String.fromCharCode(65 + index),
  text
}));

const choiceRow = (id: string, number: number, prompt: string, answer: string, options: string[]): ChoiceRow => ({
  id,
  number,
  prompt,
  correctAnswer: answer,
  options: optionList(options)
});

const lessonItem = (id: string, instruction: string, rows: ChoiceRow[]): LessonItem => ({
  id,
  type: 'listening_text_choice',
  data: { instruction, items: rows, showPinyin: false, playCount: 1, limitPlayCount: false, singlePass: true }
});

const audioSection = (id: string, audio: string, rows: ChoiceRow[]): LessonSection => {
  const first = lessonItem(id + '-p1', '第一部分：听内容，选择正确答案。', rows.slice(0, 8));
  return {
    id,
    title: 'Phần 1 · 听力 · Nghe (40 câu)',
    items: [
      { ...first, data: { ...first.data, audio, hidePrompt: true } },
      lessonItem(id + '-p2', '第二部分：听短文，选择正确答案。', rows.slice(8, 28)),
      lessonItem(id + '-p3', '第三部分：听采访，选择正确答案。', rows.slice(28))
    ]
  };
};

