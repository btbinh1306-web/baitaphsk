import { ExamLesson, Question, ReadingPassage } from '../types';
import { LessonItem, LessonSection } from '../types/lesson';

type Option = { id: string; text?: string };

const options = (texts: string[]): Option[] => texts.map((text, index) => ({ id: String.fromCharCode(65 + index), text }));
const row = (id: string, number: number, prompt: string, answer: string, choices: string[]) => ({
  id,
  number,
  prompt,
  correctAnswer: answer,
  options: options(choices)
});
const item = (id: string, type: string, instruction: string, data: Record<string, unknown>): LessonItem => ({
  id,
  type,
  data: { instruction, showPinyin: false, playCount: 1, limitPlayCount: false, singlePass: true, ...data }
});
const audioSection = (id: string, title: string, audio: string, items: LessonItem[]): LessonSection => ({
  id,
  title,
  items: items.map((entry, index) => index === 0 ? { ...entry, data: { ...entry.data, audio, hidePrompt: true } } : entry)
});
const textChoice = (id: string, number: number, prompt: string, answer: string, choices: string[]) => row(id, number, prompt, answer, choices);

const readQuestion = (id: string, number: number, prompt: string, answer: string, choices: string[]): Question => ({
  id,
  type: 'mc',
  prompt: `第${number}题：${prompt}`,
  options: choices,
  answer: answer.charCodeAt(0) - 65
});
const passage = (id: string, title: string, content: string, questions: Question[]): ReadingPassage => ({ id, title, content, questions });

const orderQuestions = (id: string, start: number, title: string, paragraphs: string[], answer: string[]): Question[] => (
  answer.map((letter, index) => ({
    id: `${id}-r${start + index}`,
    type: 'arrange',
    tier: 'tier2',
    prompt: `第${start + index}题：${title}；请选择排在第${index + 1}个位置的语段（A-E）。\n${paragraphs.map((text, paragraphIndex) => `${String.fromCharCode(65 + paragraphIndex)}：${text}`).join('\n')}`,
    wordChips: ['A', 'B', 'C', 'D', 'E'],
    acceptableAnswers: letter
  }))
);

